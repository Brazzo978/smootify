// Certificate fixtures come from the repo's tests/certs (single source of
// truth, regenerated by gen_chain.sh). They are copied into distinct
// generated directories per source set: AGP does not allow one directory to
// be shared by two source sets, and nothing is committed twice.
val certFixturesDir = rootProject.file("../tests/certs")
val certFixturesForUnitTest = layout.buildDirectory.dir("generated/certFixtures/test")
val certFixturesForAndroidTest = layout.buildDirectory.dir("generated/certFixtures/androidTest")
val certRootResForAndroidTest = layout.buildDirectory.dir("generated/certFixtures/androidTestRes")

// AGP 9's source-set decorator (DefaultAndroidLibrarySourceSet_Decorated)
// cannot be cast back to AndroidLibrarySourceSet when a generated directory
// is attached via `android.sourceSets…srcDir(...)` — that form throws a
// ClassCastException at configuration time. Use the variant API instead: a
// task with a DirectoryProperty output, wired via addGeneratedSourceDirectory.
abstract class CopyCertFixtures @javax.inject.Inject constructor(private val fs: FileSystemOperations) : DefaultTask() {
    @get:InputFiles abstract val sources: ConfigurableFileCollection
    /** Single-file sources only: rename applies to every copied file. */
    @get:Input @get:Optional abstract val renameTo: Property<String>
    /** Subdirectory below outputDir (e.g. "raw" for an Android res root). */
    @get:Input @get:Optional abstract val intoSubdir: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty
    @TaskAction fun run() {
        renameTo.orNull?.let { require(sources.files.size == 1) { "renameTo needs exactly one source file" } }
        // sync, not copy: the output directory is task-owned, so a fixture removed
        // or renamed in tests/certs must disappear here too (no stale copies)
        fs.sync {
            from(sources)
            into(intoSubdir.orNull?.let { outputDir.dir(it) } ?: outputDir)
            renameTo.orNull?.let { n -> rename { n } }
        }
    }
}
val copyCertFixturesForUnitTest = tasks.register<CopyCertFixtures>("copyCertFixturesForUnitTest") {
    sources.from(fileTree(certFixturesDir) { include("*.der") })
    outputDir.set(certFixturesForUnitTest)
}
val copyCertFixturesForAndroidTest = tasks.register<CopyCertFixtures>("copyCertFixturesForAndroidTest") {
    sources.from(fileTree(certFixturesDir) { include("*.der") })
    outputDir.set(certFixturesForAndroidTest)
}
// @raw/chain_root for the androidTest network security config: an Android
// res root needs a <type>/ subdirectory, so the file lands in raw/ below the
// registered directory (the resource name derives from the file name).
val copyCertRootResForAndroidTest = tasks.register<CopyCertFixtures>("copyCertRootResForAndroidTest") {
    sources.from(certFixturesDir.resolve("chain-root.der"))
    renameTo.set("chain_root.der")
    intoSubdir.set("raw")
    outputDir.set(certRootResForAndroidTest)
}
// AGP 9.4 hides LibraryVariant.unitTest/androidTest (superseded by the
// multi-test-suite hostTests/deviceTests maps); look the components up by
// their well-known keys.
androidComponents.onVariants { v ->
    val unitTest = v.hostTests[HostTestBuilder.UNIT_TEST_TYPE]
    val androidTest = v.deviceTests[DeviceTestBuilder.ANDROID_TEST_TYPE]
    unitTest?.sources?.resources?.addGeneratedSourceDirectory(copyCertFixturesForUnitTest) { it.outputDir }
    androidTest?.sources?.resources?.addGeneratedSourceDirectory(copyCertFixturesForAndroidTest) { it.outputDir }
    androidTest?.sources?.res?.addGeneratedSourceDirectory(copyCertRootResForAndroidTest) { it.outputDir }
}

